import "dotenv/config";
import { neon } from "@neondatabase/serverless";

const DATABASE_URL =
  process.env.NEON_DATABASE_URL ||
  process.env.DATABASE_URL;

if (!DATABASE_URL) {
  console.error("Missing NEON_DATABASE_URL (see .env.example)");
}

const sql = DATABASE_URL ? neon(DATABASE_URL) : null;

/**
 * Convert SQLite-style SQL to Postgres:
 *   - `?` placeholders  -> `$1`, `$2`, ...  (neon uses tagged template)
 *   - `datetime('now')` -> `now()`
 *   - `datetime('now', '-N unit')` -> `now() - interval 'N unit'`
 *
 * Note: all user/content data is passed as bound parameters, never embedded
 * in the SQL string, so the `?` -> `$n` conversion is safe.
 */
function toPg(sqlText, params) {
  let s = String(sqlText);

  // datetime('now', '-7 days' / '-60 seconds' / '-${n} days') forms
  s = s.replace(
    /datetime\(\s*'now'\s*,\s*'-(\d+)\s+(\w+)'\s*\)/g,
    (_, n, unit) => `now() - interval '${n} ${unit}'`
  );
  // datetime('now') form
  s = s.replace(/datetime\(\s*'now'\s*\)/g, "now()");
  // date('now') form
  s = s.replace(/date\(\s*'now'\s*\)/g, "CURRENT_DATE");

  // Replace `?` placeholders left-to-right with $1..$n
  let i = 0;
  s = s.replace(/\?/g, () => `$${++i}`);

  return {
    text: s,
    params: i ? params || [] : [],
  };
}

/**
 * Run an arbitrary query with sql.js-style `?` params.
 * Returns the affected row count for writes.
 */
export async function run(sqlText, params = []) {
  const { text, params: p } = toPg(sqlText, params);
  const result = await sql.query(text, p);
  return { rowCount: result ? result.rows.length : 0 };
}

/**
 * Run an INSERT and return the new row id.
 * Appends ` RETURNING id` to capture the generated key.
 */
export async function insert(sqlText, params = []) {
  let text = String(sqlText).trim().replace(/;\s*$/, "");
  // Convert placeholders & datetime in the INSERT portion
  const { text: convText, params: p } = toPg(text, params);
  const finalSql = `${convText} RETURNING id`;
  const result = await sql.query(finalSql, p);
  const row = result && result.rows && result.rows.length ? result.rows[0] : null;
  return row ? Number(row.id) : null;
}

/** Return the first row (object) or null. */
export async function get(sqlText, params = []) {
  const { text, params: p } = toPg(sqlText, params);
  const result = await sql.query(text, p);
  const rows = result && result.rows ? result.rows : [];
  return rows.length ? rows[0] : null;
}

/** Return all rows as an array of objects. */
export async function all(sqlText, params = []) {
  const { text, params: p } = toPg(sqlText, params);
  const result = await sql.query(text, p);
  return result && result.rows ? result.rows : [];
}

